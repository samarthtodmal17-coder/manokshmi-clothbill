/* Manokshmi ClothBill - SQLite storage adapter.
 *
 * Replaces the browser IndexedDB layer with the same six primitives the app
 * always used (getAll / get / put / add / delete / clear) plus bulkPut /
 * replaceAll for backup-restore. Each former IndexedDB object store is one
 * SQLite table: key column + a few indexed columns + the whole record as
 * JSON in `data`. The `driver` is injected so this file runs unchanged inside
 * Tauri (tauri-plugin-sql) and under Node tests (node:sqlite).
 *
 * SCHEMA below is the single source of truth: tools/gen-migration.mjs turns it
 * into src-tauri/migrations/0001_init.sql. Never edit that file by hand and
 * never change an already-shipped migration -- add 0002_*.sql instead.
 */
(function(root, factory){
  if(typeof module === 'object' && module.exports) module.exports = factory();
  else root.ClothDB = factory();
})(typeof self !== 'undefined' ? self : this, function(){

  var SCHEMA = {
    settings:            {key:'key', text:true,  indexes:[]},
    products:            {key:'id', indexes:['name','category']},
    bills:               {key:'id', indexes:['date','customerId']},
    customers:           {key:'id', indexes:['name','phone']},
    suppliers:           {key:'id', indexes:['name']},
    requirements:        {key:'id', indexes:['status','reminderDate']},
    returns:             {key:'id', indexes:['billId','date']},
    alterations:         {key:'id', indexes:['status','expectedDate']},
    attendance:          {key:'id', indexes:['staffKey','date']},
    stockAdjustments:    {key:'id', indexes:['productId','date']},
    purchaseOrders:      {key:'id', indexes:['supplierId','status']},
    purchaseInvoices:    {key:'id', indexes:['supplierId','date']},
    purchaseReturns:     {key:'id', indexes:['supplierId','date']},
    purchasePriceHistory:{key:'id', indexes:['productId','date']},
    quotations:          {key:'id', indexes:['customerId','date']},
    bookings:            {key:'id', indexes:['customerId','status','date']},
    coupons:             {key:'id', indexes:['code']},
    expenses:            {key:'id', indexes:['date','category']},
    firms:               {key:'id', indexes:['name']},
    stockTransfers:      {key:'id', indexes:['date','fromFirmId','toFirmId']},
    dayCloses:           {key:'id', indexes:['date','firmId']},
    openBills:           {key:'id', text:true, indexes:['firmId']}
  };

  function q(name){ return '"' + name + '"'; }
  function ixCol(c){ return q('ix_' + c); }

  // Builds the full CREATE script from SCHEMA (used by the migration generator and tests).
  function buildSchemaSql(){
    var out = ['-- GENERATED by tools/gen-migration.mjs from www/sqlite-adapter.js SCHEMA. Do not edit by hand.'];
    Object.keys(SCHEMA).forEach(function(name){
      var s = SCHEMA[name];
      var cols = [];
      if(s.text) cols.push(q(s.key) + ' TEXT PRIMARY KEY NOT NULL');
      else cols.push(q(s.key) + ' INTEGER PRIMARY KEY AUTOINCREMENT');
      s.indexes.forEach(function(c){ cols.push(ixCol(c)); });
      cols.push('data TEXT NOT NULL');
      cols.push("updated_at TEXT NOT NULL DEFAULT (datetime('now'))");
      out.push('CREATE TABLE IF NOT EXISTS ' + q(name) + ' (\n  ' + cols.join(',\n  ') + '\n);');
      s.indexes.forEach(function(c){
        out.push('CREATE INDEX IF NOT EXISTS ' + q('idx_' + name + '_' + c) + ' ON ' + q(name) + '(' + ixCol(c) + ');');
      });
    });
    return out.join('\n') + '\n';
  }

  function sleep(ms){ return new Promise(function(r){ setTimeout(r, ms); }); }
  function isBusy(err){ return /locked|busy/i.test((err && err.message) || String(err)); }

  function ixValue(v){
    if(v === undefined || v === null) return null;
    if(typeof v === 'boolean') return v ? 1 : 0;
    if(typeof v === 'object') return JSON.stringify(v);
    return v;
  }

  function create(driver){
    // Every operation goes through one FIFO queue: the SQL plugin pools several
    // connections, and concurrent writers are what produced "database is locked"
    // in RestroBill. One-at-a-time + busy-retry makes that impossible by design.
    var chain = Promise.resolve();
    var closed = false;

    function enqueue(fn){
      if(closed) return Promise.reject(new Error('Database is closed'));
      var p = chain.then(fn);
      chain = p.catch(function(){}); // one failure must never block the next op
      return p;
    }
    async function withRetry(fn){
      var delay = 40, last;
      for(var i = 0; i < 7; i++){
        try{ return await fn(); }
        catch(e){ last = e; if(!isBusy(e)) throw e; await sleep(delay); delay *= 2; }
      }
      throw last;
    }
    function exec(sql, params){ return withRetry(function(){ return driver.execute(sql, params || []); }); }
    function sel(sql, params){ return withRetry(function(){ return driver.select(sql, params || []); }); }
    function need(store){
      var s = SCHEMA[store];
      if(!s) throw new Error('Unknown store: ' + store);
      return s;
    }
    function toObj(s, row){
      var o = JSON.parse(row.data);
      o[s.key] = row[s.key];
      return o;
    }

    // Plain INSERT (add) or upsert (put). Returns the record's key.
    async function write(store, val, upsert){
      var s = need(store);
      var cols = [], vals = [], hasKey = val[s.key] !== undefined && val[s.key] !== null;
      if(s.text && !hasKey) throw new Error(store + ': record is missing its "' + s.key + '"');
      if(hasKey){ cols.push(q(s.key)); vals.push(val[s.key]); }
      s.indexes.forEach(function(c){ cols.push(ixCol(c)); vals.push(ixValue(val[c])); });
      cols.push('data'); vals.push(JSON.stringify(val));
      cols.push('updated_at'); vals.push(new Date().toISOString());
      var ph = vals.map(function(_, i){ return '$' + (i + 1); }).join(',');
      var sql = 'INSERT INTO ' + q(store) + ' (' + cols.join(',') + ') VALUES (' + ph + ')';
      if(upsert && hasKey){
        sql += ' ON CONFLICT(' + q(s.key) + ') DO UPDATE SET ' +
          cols.filter(function(c){ return c !== q(s.key); })
              .map(function(c){ return c + '=excluded.' + c; }).join(',');
      }
      var res = await exec(sql, vals);
      return hasKey ? val[s.key] : res.lastInsertId;
    }

    return {
      schema: SCHEMA,
      getAll: function(store){
        return enqueue(async function(){
          var s = need(store);
          var rows = await sel('SELECT ' + q(s.key) + ', data FROM ' + q(store) + ' ORDER BY ' + q(s.key));
          return rows.map(function(r){ return toObj(s, r); });
        });
      },
      get: function(store, key){
        return enqueue(async function(){
          var s = need(store);
          var rows = await sel('SELECT ' + q(s.key) + ', data FROM ' + q(store) + ' WHERE ' + q(s.key) + ' = $1', [key]);
          return rows.length ? toObj(s, rows[0]) : undefined;
        });
      },
      put: function(store, val){ return enqueue(function(){ return write(store, val, true); }); },
      add: function(store, val){ return enqueue(function(){ return write(store, val, false); }); },
      delete: function(store, key){
        return enqueue(async function(){
          var s = need(store);
          await exec('DELETE FROM ' + q(store) + ' WHERE ' + q(s.key) + ' = $1', [key]);
        });
      },
      clear: function(store){
        return enqueue(async function(){ need(store); await exec('DELETE FROM ' + q(store)); });
      },
      // Backup restore: wipe the table and load every record. Rows keep their
      // original ids so cross-references (bill -> customer, etc.) stay valid.
      replaceAll: function(store, records){
        return enqueue(async function(){
          var s = need(store);
          await exec('DELETE FROM ' + q(store));
          for(var i = 0; i < records.length; i++) await write(store, records[i], true);
        });
      },
      flushAndClose: function(){
        var p = chain.catch(function(){}).then(function(){
          closed = true;
          return driver.close ? driver.close() : undefined;
        });
        return p;
      },
      // For tests/diagnostics: run after all queued work has finished.
      idle: function(){ return chain.catch(function(){}); }
    };
  }

  return {SCHEMA: SCHEMA, buildSchemaSql: buildSchemaSql, create: create};
});
